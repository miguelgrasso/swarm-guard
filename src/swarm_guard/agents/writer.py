"""Writer agent — terminal node that produces the final output (no handoff)."""

from __future__ import annotations

from typing import Any

from strands import Agent
from strands.models.model import Model
from strands.tools.decorator import tool


@tool
def format_output(content: str) -> str:
    """Format the analysis into a polished final report.

    Args:
        content: Analysis text to format.

    Returns:
        Formatted final report string.
    """
    return f"## Final Report\n\n{content}\n\n*Generated by swarm-guard benchmark.*"


_SYSTEM_PROMPT = """\
You are a Writer agent. You are the TERMINAL node of the swarm — do NOT call handoff_to_agent.

Your role is to take the analysis from the Analyst agent and produce a polished final report
using the format_output tool.

After formatting and presenting the report, simply respond with the completed text.
Do NOT hand off to any other agent.
"""


def build_writer(model: Model) -> Agent:
    """Build and return the Writer agent (terminal node — no handoffs).

    Args:
        model: The model backend to use for inference.

    Returns:
        Configured Writer Agent ready to be added to a Swarm.
    """
    return Agent(
        model=model,
        system_prompt=_SYSTEM_PROMPT,
        tools=[format_output],
        name="writer",
        description="Produces the final written report. Terminal node — never hands off.",
    )


class Writer:
    """Convenience wrapper that constructs a Writer Agent from a model."""

    def __init__(self, model: Model) -> None:
        self.agent: Agent = build_writer(model)

    def __getattr__(self, name: str) -> Any:
        """Delegate attribute access to the underlying Agent."""
        return getattr(self.agent, name)
